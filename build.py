"""
8AI build tool - one command makes everything:

    python build.py

It will
  1. install missing Python packages (PyInstaller, PyQt6, pypdf)
  2. package 8ai.py into dist\\8AI\\8AI.exe (PyInstaller, no console)
  3. bundle llama.cpp (the llama-*-bin-win-*.zip) into dist\\8AI\\llama
  4. build  output\\8AI-<ver>-Setup.exe       (Inno Setup installer)
  5. build  output\\8AI-<ver>-Portable.exe    (ONE single exe: double-click and it runs, no install,
                                                 no extraction step; data is kept in a "data" folder beside it)
  6. build  output\\8AI-<ver>-Portable.zip    (portable folder, no install needed)

Put these files in one folder:  8ai.py  build.py  8ai.iss  make_icon.py  icon.ico
and (optional)  the llama zip  (it is found automatically).
If icon.ico is missing it is generated by make_icon.py (needs Pillow, installed automatically).

Options:
    --version 2.8.0      override the version (default: APP_VERSION in 8ai.py)
    --llama PATH         llama.cpp zip or folder (default: auto-search)
    --no-llama           do not bundle llama.cpp
    --skip-installer     skip Setup.exe (needs Inno Setup)
    --skip-portable      skip the portable zip
    --skip-single        skip the single-file Portable.exe
    --single-llama       also pack llama.cpp INSIDE the single exe (big + slower start;
                         default: llama.cpp is chosen once in Settings or put in a "llama" folder beside it)
    --no-deps            do not pip-install anything
    --clean              delete build/ and dist/ first
"""
import os, sys, re, glob, shutil, zipfile, argparse, subprocess, time

ROOT = os.path.dirname(os.path.abspath(__file__))
APP = "8AI"
MAIN = os.path.join(ROOT, "8ai.py")
ISS = os.path.join(ROOT, "8ai.iss")
ICON = os.path.join(ROOT, "icon.ico")
BUILD = os.path.join(ROOT, "build")
DIST = os.path.join(ROOT, "dist")
OUT = os.path.join(ROOT, "output")
APP_DIR = os.path.join(DIST, APP)


def log(msg):
    print("\n==> " + msg, flush=True)


def fail(msg):
    print("\n[ERROR] " + msg, flush=True)
    raise SystemExit(1)


def run(cmd, **kw):
    print("   $ " + " ".join('"%s"' % c if " " in c else c for c in cmd), flush=True)
    r = subprocess.run(cmd, **kw)
    if r.returncode != 0:
        fail("command failed (exit code %d)" % r.returncode)


def read_version():
    try:
        with open(MAIN, encoding="utf-8") as f:
            m = re.search(r'APP_VERSION\s*=\s*"([^"]+)"', f.read())
        if m:
            return m.group(1)
    except OSError:
        pass
    return "2.8.0"


# ------------------------------------------------------------------ icon
def ensure_icon(install=True):
    if os.path.isfile(ICON):
        return
    gen = os.path.join(ROOT, "make_icon.py")
    if not os.path.isfile(gen):
        print("   [warning] icon.ico and make_icon.py not found - building without an icon")
        return
    try:
        __import__("PIL")
    except ImportError:
        if not install:
            print("   [warning] Pillow missing - building without an icon")
            return
        run([sys.executable, "-m", "pip", "install", "--upgrade", "pillow"])
    run([sys.executable, gen], cwd=ROOT)


# ------------------------------------------------------------------ dependencies
def ensure_packages(install=True):
    need = []
    for mod, pip_name in (("PyInstaller", "pyinstaller"), ("PyQt6", "PyQt6"), ("pypdf", "pypdf")):
        try:
            __import__(mod)
        except ImportError:
            need.append(pip_name)
    if not need:
        print("   all Python packages are installed")
        return
    if not install:
        fail("missing packages: " + ", ".join(need) + "  (run: pip install " + " ".join(need) + ")")
    run([sys.executable, "-m", "pip", "install", "--upgrade"] + need)


# ------------------------------------------------------------------ llama.cpp
def find_llama(arg):
    if arg:
        if os.path.exists(arg):
            return arg
        fail("llama path not found: " + arg)
    if os.path.isfile(os.path.join(ROOT, "llama", "llama-server.exe")):
        return os.path.join(ROOT, "llama")
    home = os.path.expanduser("~")
    found = []
    for d in (ROOT, os.path.join(ROOT, "llama"), os.path.join(home, "Downloads"),
              os.path.join(home, "Desktop")):
        for pat in ("llama-*bin-win*.zip", "llama*win*.zip"):
            found += glob.glob(os.path.join(d, pat))
    if not found:
        return None
    return max(set(found), key=os.path.getmtime)


def prepare_llama(src, stage):
    """Extract/copy llama.cpp into `stage` so that llama-server.exe sits at its top level."""
    tmp = stage + "_tmp"
    for d in (stage, tmp):
        shutil.rmtree(d, ignore_errors=True)
    if os.path.isdir(src):
        shutil.copytree(src, tmp)
    else:
        with zipfile.ZipFile(src) as z:
            z.extractall(tmp)
    root = None
    for dp, _dn, fn in os.walk(tmp):
        if "llama-server.exe" in fn:
            root = dp
            break
    if not root:
        shutil.rmtree(tmp, ignore_errors=True)
        fail("llama-server.exe not found inside: " + src)
    shutil.copytree(root, stage)
    shutil.rmtree(tmp, ignore_errors=True)
    size = sum(os.path.getsize(os.path.join(dp, f)) for dp, _d, fs in os.walk(stage) for f in fs)
    print("   llama.cpp ready (%.1f MB): %s" % (size / 1048576, stage))
    return stage


# ------------------------------------------------------------------ PyInstaller
def build_exe():
    cmd = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--windowed",
           "--onedir", "--noupx", "--name", APP, "--distpath", DIST,
           "--workpath", os.path.join(BUILD, "pyinstaller"), "--specpath", BUILD,
           "--hidden-import", "pypdf"]
    for m in ("tkinter", "unittest", "pydoc", "test"):
        cmd += ["--exclude-module", m]
    if os.path.isfile(ICON):
        # --icon = exe icon, --add-data = copy next to the app so the window/taskbar icon works too
        cmd += ["--icon", ICON, "--add-data", ICON + os.pathsep + "."]
    cmd.append(MAIN)
    run(cmd, cwd=ROOT)
    if not os.path.isfile(os.path.join(APP_DIR, APP + ".exe")):
        fail("PyInstaller did not produce %s.exe (are you building on Windows?)" % APP)


# ------------------------------------------------------------------ single-file portable exe
def build_single_exe(version, llama_src=None):
    os.makedirs(OUT, exist_ok=True)
    name = "%s-%s-Portable" % (APP, version)
    flag = os.path.join(BUILD, "portable_exe.flag")
    os.makedirs(BUILD, exist_ok=True)
    with open(flag, "w") as f:
        f.write("8AI portable single exe")
    cmd = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean", "--windowed",
           "--onefile", "--noupx", "--name", name, "--distpath", OUT,
           "--workpath", os.path.join(BUILD, "pyinstaller_single"), "--specpath", BUILD,
           "--hidden-import", "pypdf",
           "--add-data", flag + os.pathsep + "."]
    for m in ("tkinter", "unittest", "pydoc", "test"):
        cmd += ["--exclude-module", m]
    if os.path.isfile(ICON):
        cmd += ["--icon", ICON, "--add-data", ICON + os.pathsep + "."]
    if llama_src:
        cmd += ["--add-data", llama_src + os.pathsep + "llama"]
    cmd.append(MAIN)
    run(cmd, cwd=ROOT)
    exe = os.path.join(OUT, name + ".exe")
    if not os.path.isfile(exe):
        fail("PyInstaller did not produce " + name + ".exe")
    return exe


# ------------------------------------------------------------------ Inno Setup
def find_iscc():
    cands = []
    if os.environ.get("ISCC"):
        cands.append(os.environ["ISCC"])
    for name in ("ISCC", "iscc"):
        w = shutil.which(name)
        if w:
            cands.append(w)
    try:
        import winreg
        subs = (r"SOFTWARE\Microsoft\Windows\CurrentVersion\Uninstall",
                r"SOFTWARE\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall")
        for hive in (winreg.HKEY_LOCAL_MACHINE, winreg.HKEY_CURRENT_USER):
            for sub in subs:
                for ver in ("7", "6", "5"):
                    try:
                        with winreg.OpenKey(hive, sub + "\\Inno Setup %s_is1" % ver) as k:
                            loc, _ = winreg.QueryValueEx(k, "InstallLocation")
                            cands.append(os.path.join(loc, "ISCC.exe"))
                    except OSError:
                        pass
    except ImportError:
        pass
    bases = [os.environ.get("ProgramFiles(x86)"), os.environ.get("ProgramFiles"),
             os.path.join(os.environ.get("LOCALAPPDATA", ""), "Programs")]
    for b in bases:
        if b:
            for ver in ("7", "6", "5"):
                cands.append(os.path.join(b, "Inno Setup " + ver, "ISCC.exe"))
    for c in cands:
        if c and os.path.isfile(c):
            return c
    return None


def build_installers(version):
    iscc = find_iscc()
    if not iscc:
        fail("Inno Setup (ISCC.exe) not found. Install it, or set the ISCC environment "
             "variable to its path, or run with --skip-installer.")
    if not os.path.isfile(ISS):
        fail("8ai.iss not found next to build.py")
    print("   using " + iscc)
    base = [iscc, "/Q", "/DMyAppVersion=" + version]
    run(base + [ISS], cwd=ROOT)                      # Setup.exe (unchanged)


# ------------------------------------------------------------------ portable zip
def build_portable_zip(version):
    os.makedirs(OUT, exist_ok=True)
    folder = "%s-Portable" % APP
    zpath = os.path.join(OUT, "%s-%s-Portable.zip" % (APP, version))
    if os.path.exists(zpath):
        os.remove(zpath)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for dp, _dn, fns in os.walk(APP_DIR):
            for fn in fns:
                full = os.path.join(dp, fn)
                rel = os.path.relpath(full, APP_DIR)
                z.write(full, os.path.join(folder, rel))
        z.writestr(os.path.join(folder, "portable.flag"), "8AI portable mode")
    return zpath


# ------------------------------------------------------------------ main
def main():
    ap = argparse.ArgumentParser(description="Build 8AI (exe + installer + portable)")
    ap.add_argument("--version")
    ap.add_argument("--llama")
    ap.add_argument("--no-llama", action="store_true")
    ap.add_argument("--skip-installer", action="store_true")
    ap.add_argument("--skip-portable", action="store_true")
    ap.add_argument("--skip-single", action="store_true")
    ap.add_argument("--single-llama", action="store_true")
    ap.add_argument("--no-deps", action="store_true")
    ap.add_argument("--clean", action="store_true")
    args = ap.parse_args()

    t0 = time.time()
    if os.name != "nt":
        fail("Run this on Windows (the app, llama.cpp bundle and Inno Setup are Windows-only).")
    if not os.path.isfile(MAIN):
        fail("8ai.py not found next to build.py")
    version = args.version or read_version()
    print("8AI build - version " + version)

    if args.clean:
        log("Cleaning")
        shutil.rmtree(BUILD, ignore_errors=True)
        shutil.rmtree(DIST, ignore_errors=True)
    shutil.rmtree(APP_DIR, ignore_errors=True)
    os.makedirs(OUT, exist_ok=True)

    log("1/6  Checking Python packages + icon")
    ensure_packages(install=not args.no_deps)
    ensure_icon(install=not args.no_deps)

    log("2/6  Building 8AI.exe (PyInstaller)")
    build_exe()

    log("3/6  Bundling llama.cpp")
    if args.no_llama:
        print("   skipped (--no-llama)")
    else:
        src = find_llama(args.llama)
        if not src:
            print("   [warning] no llama zip found - the app will ask the user for llama.cpp.\n"
                  "   Put llama-*-bin-win-*.zip next to build.py or use --llama PATH.")
        else:
            print("   source: " + src)
            stage = prepare_llama(src, os.path.join(BUILD, "llama_stage"))
            shutil.copytree(stage, os.path.join(APP_DIR, "llama"))

    outputs = []
    if args.skip_installer:
        log("4/6  Setup skipped")
    else:
        log("4/6  Building Setup.exe (Inno Setup)")
        build_installers(version)
        outputs.append(os.path.join(OUT, "%s-%s-Setup.exe" % (APP, version)))

    if args.skip_portable:
        log("5/6  Portable zip skipped")
    else:
        log("5/6  Building portable zip")
        outputs.append(build_portable_zip(version))

    if args.skip_single:
        log("6/6  Single-file Portable.exe skipped")
    else:
        log("6/6  Building single-file Portable.exe (PyInstaller --onefile)")
        llama_src = None
        if args.single_llama and not args.no_llama:
            llama_src = os.path.join(BUILD, "llama_stage")
            if not os.path.isdir(llama_src):
                print("   [warning] no llama.cpp found - single exe built without it")
                llama_src = None
        outputs.append(build_single_exe(version, llama_src))

    log("Done in %.0f s" % (time.time() - t0))
    for p in outputs:
        if os.path.isfile(p):
            print("   %-48s %7.1f MB" % (os.path.relpath(p, ROOT), os.path.getsize(p) / 1048576))
    print("   folder: " + OUT)
    if hasattr(os, "startfile"):
        try:
            os.startfile(OUT)
        except OSError:
            pass


if __name__ == "__main__":
    try:
        main()
    finally:
        # double-clicked from Explorer (no interactive shell): keep the window open
        if len(sys.argv) == 1 and "PROMPT" not in os.environ:
            try:
                input("\nPress Enter to close...")
            except EOFError:
                pass
